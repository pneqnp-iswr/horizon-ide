export type GameStatus = 'disconnected' | 'launching' | 'running' | 'error';

export interface FileEntry {
  path: string;
  name: string;
  is_dir: boolean;
}

export interface BuildDiagnostic {
  level: 'info' | 'warning' | 'error';
  message: string;
  file?: string;
  line?: number;
}

export interface BuildResult {
  success: boolean;
  cancelled: boolean;
  timedOut: boolean;
  outputTruncated: boolean;
  output: string;
  diagnostics: BuildDiagnostic[];
}

export interface HorizonInstallationReport {
  launchApi: string;
  horizon: string | null;
  minecraft: string | null;
  compatibleForPreview: boolean;
  gameLoadVerified: false;
  embeddedViewportVerified: false;
}

/** Exact content-addressed revision used for optimistic conflict detection. */
export interface DocumentSnapshot {
  contents: string;
  revision: string;
}

export interface ContentAttestation {
  checker: 'cargo-horizon-mod';
  checkerReportKind: 'mod';
  modId: string;
  version: string;
  contentApi: '0.2';
  sha256: string;
  officialStaticCheckPassed: true;
  targetNamespaceMatches: true;
  targetMemberVerified: false;
}

/** Evidence from a real isolated horizon-ctl item observation.
 * This is not proof the supplied archive contains the item. */
export interface GameItemSmokeReport {
  schema: 'horizon-ide.item-smoke/1';
  level: 'inventory-observed';
  itemId: string;
  packageSha256: string;
  staticAttestation: ContentAttestation;
  explicitResourcesSupplied: boolean;
  packageItemOriginVerified: false;
  gameVersion: string | null;
  launchAccepted: boolean;
  negativeControlRefused: boolean;
  exactSlotDelta: boolean;
  before: number;
  after: number;
  changedSlots: number[];
  sessionCleaned: boolean;
  notes: string[];
}

/** Source generated by the trusted official cargo-horizon-mod new command. */
export interface CreatedContentProject {
  path: string;
  modId: string;
  manifestPath: string;
  template: 'official-horizon-content';
  gameLoadVerified: false;
}

/** A data-only .hmod built by the official tool and checked against SHA-256. */
export interface ContentBuildResult {
  succeeded: true;
  artifactPath: string;
  sha256: string;
  modId: string;
  version: string;
  contentApi: '0.2';
  staticCheckPassed: true;
  inGameVerified: false;
}

/** Local-only assistant output; a proposal, never an applied edit. */
export interface LocalAiAnswer {
  provider: 'lmstudio' | 'ollama';
  model: string;
  content: string;
  localEndpoint: string;
  documentIncluded: boolean;
  proposedChangesApplied: false;
  commandsExecuted: false;
}
